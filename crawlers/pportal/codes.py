UNKNOWN = "不明"


def ministry_name(code: str) -> str:
    return MINISTRY.get((code or "").strip().upper(), UNKNOWN)


def sector_name(code: str) -> str:
    return SECTOR.get((code or "").strip().upper(), UNKNOWN)


def method_detail(code: str) -> str:
    return BIDDING_METHOD.get((code or "").strip(), (UNKNOWN, UNKNOWN))[0]


def method_bucket(code: str) -> str:
    """The `method` bucket: 一般競争 / 指名競争 / 随意契約 / その他."""
    return BIDDING_METHOD.get((code or "").strip(), (UNKNOWN, "その他"))[1]
